def line(char: str = "=", width: int = 80) -> str:
    return char * width


def fmt_float(x: float, digits: int = 10) -> str:
    return f"{x:.{digits}f}"


def gcd_many(values: Iterable[int]) -> int:
    vals = [abs(v) for v in values if v != 0]
    if not vals:
        return 0
    g = vals[0]
    for v in vals[1:]:
        g = math.gcd(g, v)
    return g


def digital_sum(n: int) -> int:
    return sum(int(ch) for ch in str(abs(n)))


def digital_root(n: int) -> int:
    n = abs(n)
    if n == 0:
        return 0
    return 1 + (n - 1) % 9


def multiplicative_order(a: int, n: int, max_iter: Optional[int] = None) -> Optional[int]:
    """Return smallest k > 0 such that a^k == 1 mod n, if gcd(a,n)=1."""
    if math.gcd(a, n) != 1:
        return None
    a %= n
    cur = 1
    max_iter = max_iter or n * n
    for k in range(1, max_iter + 1):
        cur = (cur * a) % n
        if cur == 1:
            return k
    return None


def additive_generated_size(n: int, steps: Iterable[int]) -> int:
    """Size of additive subgroup generated by steps in Z/nZ."""
    g = gcd_many([n] + list(steps))
    if g == 0:
        return 1
    return n // g


def normalize_distribution(dist: Dict[int, float], n: Optional[int] = None) -> Dict[int, float]:
    out: Dict[int, float] = {}
    for k, v in dist.items():
        kk = k % n if n else k
        out[kk] = out.get(kk, 0.0) + float(v)
    total = sum(out.values())
    if total <= 0:
        raise ValueError("Distribution has nonpositive total mass.")
    return {k: v / total for k, v in out.items() if abs(v) > 1e-15}


def convolve_mod(a: Sequence[float], step_dist: Dict[int, float], n: int) -> List[float]:
    """One convolution step on Z/nZ."""
    out = [0.0] * n
    for i, mass in enumerate(a):
        if mass == 0.0:
            continue
        for step, p in step_dist.items():
            out[(i + step) % n] += mass * p
    return out


def total_variation(dist: Sequence[float]) -> float:
    n = len(dist)
    uniform = 1.0 / n
    return 0.5 * sum(abs(x - uniform) for x in dist)


def triangular_digit_difference_distribution(base: int = 10) -> Dict[int, float]:
    """Distribution of A - B where A,B are uniform on {0,...,base-1}."""
    if base < 2:
        raise ValueError("base must be >= 2")
    denom = base * base
    return {t: (base - abs(t)) / denom for t in range(-(base - 1), base)}


def is_triangular_digit_difference(dist: Dict[int, float], base: int = 10, tol: float = 1e-12) -> bool:
    expected = triangular_digit_difference_distribution(base)
    keys = set(dist)
    if keys != set(expected):
        return False
    return all(abs(dist[k] - expected[k]) <= tol for k in expected)


def simple_is_prime(p: int) -> bool:
    if p < 2:
        return False
    if p == 2:
        return True
    if p % 2 == 0:
        return False
    r = int(math.isqrt(p))
    for d in range(3, r + 1, 2):
        if p % d == 0:
            return False
    return True


