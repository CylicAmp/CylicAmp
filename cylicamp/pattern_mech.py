def fourier_eigenvalues(n: int, step_dist: Dict[int, float]) -> List[complex]:
    """Eigenvalues of convolution random walk on Z/nZ."""
    dist = normalize_distribution(step_dist, n)
    eigs = []
    for k in range(n):
        lam = 0j
        for step, p in dist.items():
            angle = 2 * math.pi * k * step / n
            lam += p * cmath.exp(1j * angle)
        eigs.append(lam)
    return eigs


def mixing_distances(n: int, step_dist: Dict[int, float], max_steps: int = 100) -> List[Tuple[int, float]]:
    """Exact TV distances from delta_0 after t convolution steps."""
    dist = [0.0] * n
    dist[0] = 1.0
    step = normalize_distribution(step_dist, n)
    out = [(0, total_variation(dist))]
    for t in range(1, max_steps + 1):
        dist = convolve_mod(dist, step, n)
        out.append((t, total_variation(dist)))
    return out


def spectral_bound(lambda_star: float, n: int, t: int) -> float:
    if t < 0:
        return float("nan")
    return 0.5 * math.sqrt(max(n - 1, 0)) * (lambda_star ** t)


def audit_random_walk(n: int, step_dist: Dict[int, float], max_steps: int = 80) -> AuditReport:
    report = AuditReport(f"Random walk audit on Z/{n}Z")
    dist = normalize_distribution(step_dist, n)
    raw_support = sorted(step_dist)
    support = sorted(dist)

    report.pattern.append(f"State space: Z/{n}Z with {n} residues.")
    report.pattern.append(f"Raw step support: {raw_support}.")
    report.pattern.append(f"Normalized support mod {n}: {support}.")
    report.pattern.append(f"Total probability after normalization: {sum(dist.values()):.12f}.")

    gen_size = additive_generated_size(n, support)
    irreducible = (gen_size == n)
    report.mechanism.append(f"Support generates an additive subgroup of size {gen_size}.")
    report.proof.append(f"Irreducible: {irreducible}.")
    if irreducible:
        report.proof.append(
            "Because the step support generates all of Z/nZ, every state communicates with every other state."
        )
    else:
        report.proof.append(
            "Because the step support does not generate all of Z/nZ, the walk is restricted to a proper coset/subgroup."
        )

    has_self_loop = dist.get(0, 0.0) > 0
    if has_self_loop:
        report.proof.append(f"Aperiodic: True, because Pr(step=0) = {dist[0]:.12f} > 0.")
    else:
        cur = [0.0] * n
        cur[0] = 1.0
        step = dist
        good_times = []
        for t in range(1, 4 * n + 1):
            cur = convolve_mod(cur, step, n)
            if cur[0] > 1e-15:
                good_times.append(t)
        period_est = gcd_many(good_times)
        report.proof.append(
            f"Aperiodicity estimated: {period_est == 1}, based on return-time gcd {period_est} through {4*n} steps."
        )

    report.mechanism.append("Uniform distribution is stationary for any random walk on a finite group.")
    report.proof.append("Stationarity: sum_y (1/n) mu(x-y) = 1/n.")

    eigs = fourier_eigenvalues(n, dist)
    magnitudes = sorted(((abs(eigs[k]), k, eigs[k]) for k in range(n)), reverse=True)
    lambda_star, k_star, eig_star = next((m, k, e) for m, k, e in magnitudes if k != 0)
    gap = 1.0 - lambda_star
    tau_rel = float("inf") if gap <= 0 else 1.0 / gap

    report.mechanism.append("Fourier diagonalizes convolution on Z/nZ.")
    report.proof.append(
        f"Dominant nontrivial eigenvalue magnitude lambda_* = |lambda_{k_star}| = {lambda_star:.10f}."
    )
    report.proof.append(f"Spectral gap gamma = 1 - lambda_* = {gap:.10f}.")
    report.proof.append(f"Relaxation time tau_rel = 1/gamma ~= {tau_rel:.3f} steps.")

    if is_triangular_digit_difference(step_dist, base=10):
        report.mechanism.append(
            "Detected triangular digit-difference distribution A-B for decimal digits A,B in {0,...,9}."
        )
        report.mechanism.append(
            "Closed form: lambda_k = [sin(10*pi*k/n)/(10*sin(pi*k/n))]^2, with lambda_0=1 by continuity."
        )

    distances = mixing_distances(n, dist, max_steps=max_steps)
    key_rows = [1, 5, 10, 15, 20, 25, 30, 50]
    rows = []
    for t in key_rows:
        if t <= max_steps:
            rows.append(
                f"t={t}: TV={distances[t][1]:.6g}, spectral_bound<={spectral_bound(lambda_star, n, t):.6g}"
            )
    report.proof.append("Selected convergence distances: " + "; ".join(rows))

    for eps in [0.01, 0.001]:
        first = next((t for t, tv in distances if tv < eps), None)
        if first is not None:
            report.proof.append(f"Exact computed t_mix({eps}) from delta_0 is <= {first} steps.")
        elif 0 < lambda_star < 1:
            t_bound = math.ceil(math.log((2 * eps) / math.sqrt(n - 1)) / math.log(lambda_star))
            report.proof.append(f"Spectral bound gives t_mix({eps}) <= about {t_bound} steps.")

    report.compression.append(
        f"Random walk on Z/{n}Z has lambda_*={lambda_star:.10f}, gamma={gap:.10f}; "
        "it mixes on a tens-of-steps scale if gamma is large."
    )
    report.application.extend([
        "Use to reject inflated convergence claims.",
        "Use to estimate simulation length before brute forcing.",
        "Use as a toy randomness/mixing test for modular systems.",
    ])

    if n == 37 and abs(lambda_star - 0.7835169601) < 1e-6:
        report.verdict.append(
            "For the Z/37Z triangular walk, convergence is O(10) to O(100) steps, not 10^7 to 10^8."
        )
    else:
        report.verdict.append(
            "Markov audit complete; use lambda_* and exact TV values to judge convergence scale."
        )
    return report


