@dataclass
class AuditReport:
    title: str
    pattern: List[str] = field(default_factory=list)
    mechanism: List[str] = field(default_factory=list)
    proof: List[str] = field(default_factory=list)
    compression: List[str] = field(default_factory=list)
    application: List[str] = field(default_factory=list)
    verdict: List[str] = field(default_factory=list)

    def add(self, section: str, text: str) -> None:
        getattr(self, section.lower()).append(text)

    def render_section(self, name: str, items: List[str]) -> str:
        body = "\n".join(f" - {x}" for x in items) if items else " - None."
        return f"{name}:\n{body}"

    def render(self) -> str:
        parts = [
            line("="),
            f"VIREON PATTERN-MECH AUDIT: {self.title}",
            line("="),
            self.render_section("PATTERN", self.pattern),
            self.render_section("MECHANISM", self.mechanism),
            self.render_section("PROOF", self.proof),
            self.render_section("COMPRESSION", self.compression),
            self.render_section("APPLICATION", self.application),
            self.render_section("VERDICT", self.verdict),
        ]
        return "\n".join(parts)


