def orbit_mod(seed: int, multiplier: int, modulus: int, max_steps: Optional[int] = None) -> Tuple[List[int], int]:
    """Return orbit seed, seed*a, seed*a^2,... mod n until repeat, plus repeat index."""
    if modulus <= 0:
        raise ValueError("modulus must be positive")
    max_steps = max_steps or (modulus * 2 + 10)
    seen: Dict[int, int] = {}
    orbit: List[int] = []
    x = seed % modulus
    for _ in range(max_steps):
        if x in seen:
            return orbit, seen[x]
        seen[x] = len(orbit)
        orbit.append(x)
        x = (x * multiplier) % modulus
    return orbit, -1


def audit_modular_orbit(modulus: int, multiplier: int, seed: int) -> AuditReport:
    report = AuditReport(f"Modular orbit audit: seed={seed}, multiplier={multiplier}, mod={modulus}")
    a = multiplier % modulus
    s = seed % modulus
    order = multiplicative_order(a, modulus)
    orbit, repeat_at = orbit_mod(seed, multiplier, modulus)

    repeat_label = str(orbit[repeat_at]) if repeat_at >= 0 else "?"
    report.pattern.append(
        f"Orbit under x -> {a}x mod {modulus}: {' -> '.join(map(str, orbit))} -> {repeat_label}."
    )

    if order is not None:
        subgroup = []
        cur = 1
        for _ in range(order):
            subgroup.append(cur)
            cur = (cur * a) % modulus
        report.mechanism.append(f"Multiplier {a} is a unit mod {modulus}; ord_{modulus}({a}) = {order}.")
        report.mechanism.append(
            f"Generated multiplicative subgroup: <{a}> = {{{', '.join(map(str, subgroup))}}}."
        )
        coset = sorted({(s * h) % modulus for h in subgroup})
        report.mechanism.append(
            f"Seed orbit is the coset {s}*<{a}> = {{{', '.join(map(str, coset))}}}."
        )
        report.proof.append(f"{a}^{order} = 1 mod {modulus}; no smaller positive exponent returns to 1.")
        report.compression.append(
            f"The visible orbit is not the subgroup itself; it is a coset orbit generated by multiplying seed {s} by <{a}>."
        )
    else:
        report.mechanism.append(
            f"Multiplier {a} is not a unit mod {modulus}; multiplicative order is undefined."
        )
        report.proof.append(
            "Orbit still exists as repeated multiplication in a finite set, but it is not a unit-group subgroup orbit."
        )
        report.compression.append(
            "Finite modular multiplication creates a cycle, but not necessarily a group orbit."
        )

    if modulus == 37 and a == 26:
        report.proof.append(
            "For the known triad: 137 = 248 = 359 = 26 mod 37 because consecutive differences are 111 = 3x37."
        )
        report.proof.append("26^2 = 10 mod 37 and 26^3 = 1 mod 37, so <26> = {1, 26, 10}.")
        if seed % modulus == 14:
            report.proof.append("14*{1,26,10} = {14,31,29}, matching the heartbeat/coset orbit.")

    report.application.extend([
        "Use to classify residue cycles.",
        "Use to separate true subgroup structure from symbolic naming.",
        "Use as a finite-state orbit verifier.",
    ])
    report.verdict.append("Orbit structure is valid when stated as an order/subgroup/coset claim.")
    return report


