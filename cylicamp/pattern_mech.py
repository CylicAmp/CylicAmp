def decimal_repetend(numerator: int, denominator: int, max_digits: int = 10000) -> Tuple[str, str, int]:
    """Long-division repetend finder. Returns nonrepeating_digits, repeating_block, period_length."""
    if denominator == 0:
        raise ZeroDivisionError("denominator cannot be zero")
    num = abs(numerator)
    den = abs(denominator)
    remainder = num % den
    seen: Dict[int, int] = {}
    digits: List[str] = []
    idx = 0
    while remainder and remainder not in seen and idx < max_digits:
        seen[remainder] = idx
        remainder *= 10
        digit = remainder // den
        remainder %= den
        digits.append(str(digit))
        idx += 1
    if remainder == 0:
        return "".join(digits), "", 0
    if idx >= max_digits:
        raise RuntimeError("max_digits reached before period detected")
    start = seen[remainder]
    nonrep = "".join(digits[:start])
    rep = "".join(digits[start:])
    return nonrep, rep, len(rep)


def audit_decimal_repetend(numerator: int, denominator: int) -> AuditReport:
    report = AuditReport(f"Decimal repetend audit: {numerator}/{denominator}")
    nonrep, rep, period = decimal_repetend(numerator, denominator)
    den_abs = abs(denominator)

    report.pattern.append(f"Input fraction: {numerator}/{denominator}.")
    if period:
        report.pattern.append(f"Repeating block: {rep} with period {period}.")
        dr_val = digital_root(int(rep))
        ds_val = digital_sum(int(rep))
        report.pattern.append(f"Digital sum of repeating block: {ds_val}; digital root: {dr_val}.")
    else:
        report.pattern.append(f"Terminating decimal with nonrepeating digits: {nonrep or '0'}.")

    if math.gcd(den_abs, 10) == 1 and period:
        order = multiplicative_order(10, den_abs)
        report.mechanism.append(f"Since gcd({den_abs},10)=1, the repetend period equals ord_{den_abs}(10) = {order}.")
    elif period:
        reduced_den = den_abs
        while reduced_den % 2 == 0:
            reduced_den //= 2
        while reduced_den % 5 == 0:
            reduced_den //= 5
        order = multiplicative_order(10, reduced_den) if reduced_den > 1 else 0
        report.mechanism.append(
            f"Denominator has factors 2/5; repeating behavior comes from reduced denominator {reduced_den}, with order {order}."
        )
    else:
        report.mechanism.append("Denominator factors only into 2s and 5s after cancellation, so decimal terminates.")

    if period and period % 2 == 0:
        half = period // 2
        a = int(rep[:half])
        b = int(rep[half:])
        target = 10 ** half - 1
        report.pattern.append(f"Split halves: {rep[:half]} and {rep[half:]}; sum = {a+b}.")
        if a + b == target:
            report.proof.append(f"Split-complement verified: {a} + {b} = {target}.")
            if pow(10, half, den_abs) == den_abs - 1:
                report.mechanism.append(f"Mechanism found: 10^{half} = -1 mod {den_abs}.")
                report.proof.append(
                    f"Because 10^{half} = -1 mod {den_abs}, the two half-blocks are complementary to 10^{half}-1."
                )
                report.compression.append(
                    f"10^{half} = -1 mod {den_abs}, so the repetend of {numerator}/{denominator} "
                    f"splits into complementary halves summing to {target}."
                )
            else:
                report.mechanism.append(
                    f"Split complement exists, but 10^{half} != -1 mod {den_abs}; "
                    "numerator/cancellation details may be responsible."
                )
                report.compression.append(
                    f"The repetend halves sum to {target}, but the denominator-level -1 congruence was not detected."
                )
        else:
            report.proof.append(f"No split-complement: {a} + {b} = {a+b}, not {target}.")
            report.compression.append(f"Period {period} detected; no complementary half split.")

    if numerator == 103 and denominator == 137:
        q, r = divmod(7775, denominator)
        report.proof.append(
            f"Check 7775 relation: 7775 = {q}x137 + {r}; therefore 7775/137 = {q} + {r}/137."
        )
        if r == numerator:
            report.proof.append("So 7775/137 preserves the same fractional repetend as 103/137.")

    report.application.extend([
        "Use as a decimal-pattern validator.",
        "Use to decide whether a visual digit pattern is forced by modular arithmetic or merely decorative.",
    ])
    report.verdict.append("Pattern is accepted only where the modular mechanism explains it.")
    return report


