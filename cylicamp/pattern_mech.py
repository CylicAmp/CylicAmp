# D. Divisibility/parity theorem audit
# =============================================================================

def audit_forbidden_odd_dimension(p: int, m: int, n: int, divisor: int = 7, offset: int = 2) -> AuditReport:
    report = AuditReport(f"Divisibility/parity audit: p={p}, m={m}, n={n}")
    mn = m * n
    numerator_val = mn - offset
    is_sq_sum = (m * m + n * n == p)
    is_prime_p = simple_is_prime(p)
    quotient_exists = (numerator_val % divisor == 0)
    quotient = numerator_val // divisor if quotient_exists else None

    report.pattern.append(f"Claim object: p = {p}, representation candidate {m}^2 + {n}^2 = {m*m+n*n}.")
    report.pattern.append(f"mn = {mn}; expression d = (mn - {offset})/{divisor}.")
    if quotient_exists:
        report.pattern.append(f"d = {quotient}.")
    else:
        report.pattern.append("d is not an integer.")

    report.mechanism.append("This is primarily a parity/divisibility filter.")
    report.proof.append(f"p is prime by simple test: {is_prime_p}.")
    report.proof.append(f"p = m^2+n^2 representation valid: {is_sq_sum}.")

    if mn % 2 == 0 and offset % 2 == 0 and divisor % 2 == 1:
        report.proof.append(f"mn is even and offset {offset} is even, so mn-{offset} is even.")
        report.proof.append(
            f"Divisor {divisor} is odd. If an even integer is divisible by an odd integer, the quotient remains even."
        )
        if quotient_exists:
            report.proof.append(f"Here quotient d={quotient}; even={quotient % 2 == 0}.")
        report.compression.append(
            f"If mn is even and d=(mn-{offset})/{divisor} is an integer with odd divisor {divisor}, then d must be even."
        )
    else:
        report.proof.append(
            "The clean parity lemma does not apply because one condition fails: mn even, offset even, divisor odd."
        )
        report.compression.append("No forced evenness without the parity conditions.")

    if p == 137 and {abs(m), abs(n)} == {4, 11}:
        report.proof.append("Example: 137 = 4^2+11^2, mn=44, d=(44-2)/7=6.")

    report.application.extend([
        "Use as a search-space filter: reject odd d immediately when the lemma conditions hold.",
        "Use to distinguish a true theorem from a deeper-looking but elementary parity consequence.",
    ])

    if quotient_exists and quotient is not None and quotient % 2 == 0:
        report.verdict.append("No forbidden odd dimension exists for this case.")
    elif quotient_exists:
        report.verdict.append(
            "Odd quotient found; parity assumptions must have failed or the theorem statement is wrong."
        )
    else:
        report.verdict.append("Expression is not integral, so the dimension condition does not activate.")
    return report


