def run_demo() -> str:
    reports: List[AuditReport] = []

    # 1. Decimal repetend: 103/137
    reports.append(audit_decimal_repetend(103, 137))

    # 2. Modular orbit: modulus 37, multiplier 26, seed 14
    reports.append(audit_modular_orbit(37, 26, 14))

    # 3. Random walk on Z/37Z with triangular steps -9..9
    tri = triangular_digit_difference_distribution(10)
    reports.append(audit_random_walk(37, tri, max_steps=80))

    # 4. Forbidden odd dimension check for 137 = 4^2 + 11^2
    reports.append(audit_forbidden_odd_dimension(137, 4, 11))

    return "\n\n".join(r.render() for r in reports)


def main() -> None:
    parser = argparse.ArgumentParser(description="VIREON Pattern-Mech Audit Engine")
    parser.add_argument("--demo", action="store_true", help="Run built-in demo audits.")
    parser.add_argument("--decimal", nargs=2, type=int, metavar=("NUM", "DEN"),
                        help="Audit decimal repetend NUM/DEN.")
    parser.add_argument("--orbit", nargs=3, type=int, metavar=("MODULUS", "MULTIPLIER", "SEED"),
                        help="Audit modular orbit.")
    parser.add_argument("--walk37", action="store_true",
                        help="Audit triangular digit-difference walk on Z/37Z.")
    parser.add_argument("--parity137", action="store_true",
                        help="Audit forbidden odd dimension example 137=4^2+11^2.")
    args = parser.parse_args()

    reports: List[AuditReport] = []

    if args.demo or not any([args.decimal, args.orbit, args.walk37, args.parity137]):
        print(run_demo())
        return

    if args.decimal:
        num, den = args.decimal
        reports.append(audit_decimal_repetend(num, den))

    if args.orbit:
        modulus, multiplier, seed = args.orbit
        reports.append(audit_modular_orbit(modulus, multiplier, seed))

    if args.walk37:
        reports.append(audit_random_walk(37, triangular_digit_difference_distribution(10)))

    if args.parity137:
        reports.append(audit_forbidden_odd_dimension(137, 4, 11))

    print("\n\n".join(r.render() for r in reports))


if __name__ == "__main__":
    main()
