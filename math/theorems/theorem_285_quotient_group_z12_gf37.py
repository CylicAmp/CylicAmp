ANTIPODAL_PAIRS = [
    ("IC","NEG_H"),("DARK_A","NQR17"),("C3","D7"),
    ("CAS_EXT","SEED"),("TESLA","C9"),("SA_ST_A","SA_ST_B"),
]

def orbit_of(x):
    r = x % 37
    if r == 0: return "SEAM"
    for name, s in ORBITS.items():
        if r in s: return name
    raise ValueError(x)

# ── Part 1: Orbit product is well-defined ─────────────────────────────────────

print("Part 1: Orbit product is well-defined — coset multiplication")

# For any x∈O₁, y∈O₂: x=a₁r₁ (a₁∈IC), y=a₂r₂ (a₂∈IC)
# xy = (a₁a₂)(r₁r₂); a₁a₂∈IC (IC is a subgroup) → xy ∈ (r₁r₂)·IC

def orbit_product(O1, O2):
    """Returns the orbit of the product of any elements from O1 and O2."""
    r1 = next(iter(ORBITS[O1]))
    r2 = next(iter(ORBITS[O2]))
    result = orbit_of(r1 * r2)
    # Verify consistency: all element pairs give the same orbit
    for x in ORBITS[O1]:
        for y in ORBITS[O2]:
            assert orbit_of(x * y) == result, f"{x}*{y} ≠ {result}"
    return result

# Sample checks
