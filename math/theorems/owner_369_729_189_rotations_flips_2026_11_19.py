def dr(n):
    return 0 if n == 0 else 1 + (n - 1) % 9


def flip(n):
    return int(f"{n:03d}"[::-1])


def ways(s):
    """every way of cutting the digit string and adding the parts"""
    out = []
    for cuts in product([0, 1], repeat=len(s) - 1):
        parts, cur = [], s[0]
        for c, ch in zip(cuts, s[1:]):
            if c:
                parts.append(cur)
                cur = ch
            else:
                cur += ch
        out.append(sum(int(p) for p in parts + [cur]))
    return out


def orderings(n):
    return sorted({"".join(p) for p in permutations(str(n))})


