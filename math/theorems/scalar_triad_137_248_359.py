    print(f"  103 mod 37 = {103%37},  137⁻¹ mod 37 = {pow(137,-1,37)}")
    print(f"  103/137 mod 37 = 29 × 10 = {29*10} ≡ {(29*10)%37}  ∈ {{14,31,29}}")

