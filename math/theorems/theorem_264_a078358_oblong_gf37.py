print(f"  Criterion: r oblong iff 1+4r is QR mod 37")
print(f"  C9 discriminants: {{20∈DARK_A, 6∈TESLA, 14∈C9}} — all NQR")
print(f"  CAS_EXT = Fibonacci entry orbit: fully in oblong residues")
print(f"  SA_ST_A = {{3²,3×4,4²}}: square-pronic-square triple, fully oblong")
print(f"  Polarity bridge: 29∈C9 (non-oblong) generates 19∈CAS_EXT (oblong)")
print(f"  C9 twin prime pair (29,31): both orbit-internal, both non-oblong residues")
