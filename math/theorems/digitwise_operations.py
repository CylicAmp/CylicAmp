def test_tables_and_local_ring():
    """THEOREM 10."""
    add, sub, mul = table(c_add), table(c_sub), table(c_mul)
    # additive group: 9 is the identity, every element invertible
    for a in RING:
        assert add[(a, 9)] == a
        assert add[(a, c_neg(a))] == 9
        assert sub[(a, a)] == 9
    # multiplicative: 1 is the identity
    for a in RING:
        assert mul[(a, 1)] == a
        assert mul[(a, 9)] == 9                       # 9 is the zero
    # units and the ideal
    assert UNITS == [1, 2, 4, 5, 7, 8]
    assert IDEAL == [3, 6, 9]
    assert len(UNITS) == 6                            # phi(9)
    assert INVERSES == {1: 1, 2: 5, 4: 7, 5: 2, 7: 4, 8: 8}
    for u, iv in INVERSES.items():
        assert mul[(u, iv)] == 1
    for d in IDEAL:
        assert c_div(1, d) is None                    # no inverse
    # (3) is an ideal
    for a in IDEAL:
        for x in RING:
            assert mul[(a, x)] in IDEAL, (a, x)
    # and it squares to zero -- the whole point
    assert {mul[(a, b)] for a in IDEAL for b in IDEAL} == {9}
    assert all(mul[(d, d)] == 9 for d in IDEAL)
    assert NILPOTENCY_INDEX == 2
    # local: exactly one maximal ideal, residue field F_3
    assert IDEAL == sorted({mul[(3, k)] for k in RING})
    assert len(RING) // len(IDEAL) == RESIDUE_FIELD_ORDER == 3
    # zero divisors are exactly the non-units
    zd = [a for a in RING if a != 9 and any(mul[(a, b)] == 9 for b in RING if b != 9)]
    assert sorted(zd) == [3, 6]
    assert sorted(zd + [9]) == IDEAL


def test_two_lattices():
    """THEOREM 11: both lattices are divisor lattices."""
    A = additive_subgroups()
    assert sorted(A) == [1, 3, 9]                     # divisors of 9
    assert A[1] == [9] and A[3] == [3, 6, 9] and A[9] == RING
    assert len(A) == 3
    for order, H in A.items():
        assert len(H) == order
        for a in H:
            for b in H:
                assert c_add(a, b) in H               # closed
    U = unit_subgroups()
    assert sorted(U) == [1, 2, 3, 6]                  # divisors of 6
    assert len(U) == 4
    assert U[1] == [1] and U[2] == [1, 8] and U[3] == [1, 4, 7]
    assert U[6] == UNITS
    for order, H in U.items():
        assert len(H) == order
        for a in H:
            for b in H:
                assert c_mul(a, b) in H
    # 2 is a primitive root mod 9, which IS ord_9(2) = 6
    assert multiplicative_order(PRIMITIVE_ROOT) == UNIT_GROUP_ORDER == 6
    assert sorted({digital_root(pow(2, k, 9)) for k in range(6)}) == UNITS
    # the crossed duality
    assert sorted({c_mul(u, u) for u in UNITS}) == SQUARES_OF_UNITS == [1, 4, 7]
    assert sorted({c_mul(c_mul(u, u), u) for u in UNITS}) == CUBES_OF_UNITS == [1, 8]
    assert sorted([u for u in UNITS if c_pow(u, 3) == 1]) == SQUARES_OF_UNITS
    assert sorted([u for u in UNITS if c_pow(u, 2) == 1]) == CUBES_OF_UNITS
    assert CUBES_OF_UNITS == sorted({1, c_neg(1)})    # = {+1,-1}


def test_exponentiation():
    """THEOREM 12."""
    for u in UNITS:
        o = multiplicative_order(u)
        assert o in (1, 2, 3, 6)
        assert CARMICHAEL_9 % o == 0                  # order divides lambda(9)
        assert c_pow(u, CARMICHAEL_9) == 1            # Euler
    assert ({u: multiplicative_order(u) for u in UNITS}
            == {1: 1, 2: 6, 4: 3, 5: 6, 7: 3, 8: 2})
    # non-units absorb at exponent 2 and never come back
    for d in IDEAL:
        assert c_pow(d, 1) == d
        for k in range(2, 12):
            assert c_pow(d, k) == 9, (d, k)
    # so the sequence d^k has period 6 on units, and is eventually 9 off them
    assert [c_pow(2, k) for k in range(1, 7)] == [2, 4, 8, 7, 5, 1]
    assert [c_pow(3, k) for k in range(1, 7)] == [3, 9, 9, 9, 9, 9]


def test_palindrome_iff_commutative():
    """THEOREM 13, both directions."""
    v = digits(SHEET)
    for name, op in OPS.items():
        comm = is_commutative(op)
        assert comm == (name in COMMUTATIVE), name
        got = text(bar(v, op))
        assert got == BAR_TABLE[name], (name, got)
        # the forward direction, swept
        all_pal = all(is_palindrome(bar(digits(n), op))
                      for n in range(10000, 100000, 11))
        assert all_pal == comm, name
    # (<=) commutativity gives it for every N and every length
    for name in COMMUTATIVE:
        op = OPS[name]
        for r in (2, 3, 4, 5):
            lo, hi = 10 ** (r - 1), 10 ** r
            for n in range(lo, hi, max(1, (hi - lo) // 400)):
                assert is_palindrome(bar(digits(n), op)), (name, n)
    # (=>) a single non-commuting pair already breaks it: build the witness
    for name in NONCOMMUTATIVE:
        op = OPS[name]
        a, b = next((a, b) for a in RING for b in RING if op(a, b) != op(b, a))
        n = int(f'{a}{b}')                            # N = ab, reverse = ba
        assert not is_palindrome(bar(digits(n), op)), (name, a, b)


def test_antipalindrome_and_the_forced_middle():
    """THEOREM 14."""
    assert is_anticommutative(c_sub)
    v = digits(SHEET)
    A = bar(v, c_sub)
    assert text(A) == '15948'
    assert is_antipalindrome(A)
    assert not is_palindrome(A)
    # the middle column of an odd-length antipalindrome is forced to 9,
    # because it is its own negative and 2 is a unit
    assert pow(2, -1, 9) == 5
    for r in (3, 5, 7):
        lo, hi = 10 ** (r - 1), 10 ** r
        step = max(1, (hi - lo) // 3000)
        for n in range(lo, hi, step):
            w = bar(digits(n), c_sub)
            assert is_antipalindrome(w), n
            assert w[r // 2] == 9, (n, w)
    # exhaustively at r = 3 and r = 5
    assert all(bar(digits(n), c_sub)[1] == 9 for n in range(100, 1000))
    assert all(bar(digits(n), c_sub)[2] == 9 for n in range(10000, 100000))
    # even length has no self-paired column, so nothing is forced
    vals = {tuple(bar(digits(n), c_sub)) for n in range(1000, 10000)}
    assert any(9 not in w for w in vals)


def test_eigenspace_split():
    """THEOREM 15: the two projections recover N, and sum to the doubling."""
    zeros = 0
    for n in range(10000, 100000, 7):
        v = ring_digits(n)                 # a 0 digit IS the class 9
        if any(c == '0' for c in str(n)):
            zeros += 1
        P, A = palindromic_part_x2(v), antipalindromic_part_x2(v)
        assert is_palindrome(P) and is_antipalindrome(A)
        S = [digital_root(P[i] + A[i]) for i in range(5)]
        assert S == [digital_root(2 * d) for d in v]          # P + A = 2N
        assert recover(v) == v                                 # 2^-1 reassembles
    assert zeros > 0                        # the 0-digit case really was covered
    # and recover is only an identity on ring representatives: a literal
    # 0 comes back as 9, which is the same class, not the same character
    assert recover(digits(10234)) != digits(10234)
    assert recover(ring_digits(10234)) == ring_digits(10234)
    # the worked instance: the user's two blocks, joined
    v = digits(SHEET)
    assert text(palindromic_part_x2(v)) == '13331'
    assert text(antipalindromic_part_x2(v)) == '15948'
    assert text([digital_root(13331 // 10 ** (4 - i) % 10 +
                              15948 // 10 ** (4 - i) % 10) for i in range(5)]) == '28379'
    assert text([digital_root(2 * d) for d in v]) == '28379'
    # ranks, and the direct sum is genuine
    assert ranks(5) == (3, 2) and sum(ranks(5)) == 5
    assert ranks(4) == (2, 2) and ranks(7) == (4, 3)
    npal = len({tuple(bar(digits(n), c_add)) for n in range(10000, 100000)})
    assert npal <= 9 ** 3
    pal_all = {(a, b, c, b, a) for a in RING for b in RING for c in RING}
    ant_all = {(a, b, 9, digital_root(-b), digital_root(-a))
               for a in RING for b in RING}
    assert len(pal_all) == 9 ** 3 == 729
    assert len(ant_all) == 9 ** 2 == 81
    assert len(pal_all) * len(ant_all) == 9 ** 5                # a direct sum
    # and the only vector in both eigenspaces is the zero one
    both = pal_all & ant_all
    assert both == {(9, 9, 9, 9, 9)}, both


def test_eleven_powers_and_pascal():
    """THEOREM 16: the same no-carry condition, twice."""
    for k in range(5):
        assert str(11 ** k) == ''.join(str(c) for c in pascal_row(k))
        assert max(pascal_row(k)) < 10
        assert eleven_power_is_palindromic(k)
    assert max(pascal_row(5)) == 10 == PASCAL_BREAKS_AT * 2
    assert not eleven_power_is_palindromic(5)
    assert 11 ** 4 == 14641 and 11 ** 3 == 1331 and 11 ** 2 == 121
    # gcd and min across the bar both land on 11^4
    v = digits(SHEET)
    assert text(bar(v, OPS['gcd'])) == '14641' == str(11 ** 4)
    assert text(bar(v, OPS['min'])) == '14641'
    assert text(bar(v, OPS['lcm'])) == text(bar(v, OPS['max'])) == '98689'
    # the no-carry condition is the one that bounds the layer class
    layer = [n for n in range(10000, 100000)
             if str(n) == str(n)[::-1]
             and all(str(k * n) == str(k * n)[::-1] for k in (1, 2, 3))]
    assert len(layer) == 48
    assert all(max(digits(n)) <= 3 for n in layer)
    assert all(max(pascal_row(k)) <= 3 for k in range(3))


def test_does_not_prove_too_much():
    """Guard every boundary."""
    # Z/9Z is NOT a field: 3 and 6 have no inverse
    assert c_div(1, 3) is None and c_div(1, 6) is None
    assert len(UNITS) == 6 < 8                        # a field of order 9 has 8 units
    # the ideal absorbs under x but only TRAPS under +
    assert {c_mul(a, b) for a in IDEAL for b in IDEAL} == {9}
    assert {c_add(a, b) for a in IDEAL for b in IDEAL} == {3, 6, 9}
    assert len({c_add(a, b) for a in IDEAL for b in IDEAL}) == 3
    # commutativity must hold on EVERY pair, not merely on some: pow
    # agrees on 2^4 = 4^2 = 7 and still fails the theorem overall
    assert c_pow(2, 4) == c_pow(4, 2) == 7
    agree = [(a, b) for a in RING for b in RING if c_pow(a, b) == c_pow(b, a)]
    disagree = [(a, b) for a in RING for b in RING if c_pow(a, b) != c_pow(b, a)]
    assert agree and disagree                 # both kinds of pair exist
    assert not is_commutative(OPS['pow'])
    assert (2, 4) in agree and (2, 3) in disagree
    # division is anticommutative only where defined; it is not a clean
    # antipalindrome generator the way subtraction is
    assert is_anticommutative(c_sub)
    assert not is_antipalindrome(bar(digits(SHEET), OPS['div']))
    # the forced middle 9 is an ODD-length statement only: at even length
    # no column is paired with itself, so nothing is forced anywhere
    even = [bar(ring_digits(n), c_sub) for n in range(1000, 10000)]
    assert any(9 not in w for w in even)
    w = bar(ring_digits(1234), c_sub)
    assert text(w) == '6813'
    assert is_antipalindrome(w) and 9 not in w
    for j in range(4):
        assert any(w[j] != 9 for w in even), j
    # 11^k palindromy stops; it is not a theorem about all k
    assert not any(eleven_power_is_palindromic(k) for k in range(5, 12))
    # and these results say nothing about ordinary (carrying) arithmetic
    assert str(14689 + 98641) == '113330' != '113330'[::-1]


