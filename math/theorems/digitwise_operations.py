"""
EVERY OPERATION ON THE COLUMNWISE SHEET
================================================================

digitwise_sheets.py worked one operation -- columnwise addition.  This
file does the rest, and the rest turns out to explain the first.

The carrier is the same: a digit string of length r, each entry reduced
to its digital root, i.e. a vector in (Z/9Z)^r written with 9 for 0.
Running ALL of arithmetic on it column by column exposes three things
addition alone could not show.

  (a) Z/9Z is not a field.  Under multiplication it is a LOCAL RING
      whose maximal ideal is exactly {3,6,9}, and that ideal SQUARES TO
      ZERO.  So the "bottom third" of digitwise_sheets THEOREM 2 was
      never just a closed subset -- it is the nilpotent ideal, and that
      is why it absorbs.  Under + and doubling it merely traps you;
      under x it kills you in one step.

  (b) The palindrome of digitwise_sheets THEOREM 4 has nothing to do
      with addition.  N o reverse(N) is a palindrome for every N if and
      only if o is COMMUTATIVE.  Addition was one of ten witnesses.

  (c) The non-commutative operations are not failures, they are the
      other eigenspace.  Reversal is an involution, 2 is invertible mod
      9, so (Z/9Z)^r splits as palindromes (+) antipalindromes, and the
      across-the-bar SUM and across-the-bar DIFFERENCE are twice the two
      projections.  They add back to the doubling.

Grading, as elsewhere in this repository:

  Level 1  proved parameter-free, or settled by exhausting a finite set
  Level 2  verified over a bounded range

Everything here is Level 1.

  THEOREM 10  the four tables (+, -, x, /), and Z/9Z as a local ring:
              units = (Z/9Z)* of order phi(9) = 6, maximal ideal
              (3) = {3,6,9}, (3)^2 = 0, residue field F_3.      Level 1
  THEOREM 11  the two group lattices.  (Z/9Z,+) is cyclic of order 9
              with 3 subgroups, one per divisor of 9.  (Z/9Z)* is
              cyclic of order 6 generated by 2 -- so ord_9(2) = 6 is
              just "2 is a primitive root mod 9" -- with 4 subgroups,
              one per divisor of 6.  The order-3 subgroup {1,4,7} is
              the squares and the kernel of cubing; the order-2
              subgroup {1,8} = {+1,-1} is the cubes and the kernel of
              squaring.  The duality is crossed.                 Level 1
  THEOREM 12  exponentiation: lambda(9) = 6 bounds every unit's order,
              which is 1, 2, 3 or 6; every non-unit absorbs to 9 at
              exponent 2.                                        Level 1
  THEOREM 13  N o reverse(N) is a palindrome for EVERY N  <=>  o is
              commutative.  Both directions proved.              Level 1
  THEOREM 14  for non-commutative o with a o b = -(b o a) -- subtraction
              and division -- the result is an ANTIpalindrome, and for
              odd r the middle column is forced to 9, since it is its
              own negative and 2 is invertible.                  Level 1
  THEOREM 15  (Z/9Z)^r = Pal (+) Anti as Z/2Z-modules under reversal.
              For r = 5 the ranks are 3 and 2.  N (+) rev(N) and
              N (-) rev(N) are twice the projections and sum to 2N, so
              13331 (+) 15948 = 28379 recovers the doubling.     Level 1
  THEOREM 16  11^k is Pascal's row k, palindromic exactly while no
              binomial coefficient reaches 10.  That is the same
              no-carry condition that bounds the 48-member layer class
              in digitwise_sheets THEOREM 8, and gcd and min across the
              bar both land on 11^4 = 14641.                     Level 1

ASSOCIATIONS.  (Z/9Z)* = Z/6Z here sits beside GF(37)* = Z/12Z in
palindrome_gf37.py: both cyclic, both with subgroup lattice equal to the
divisor lattice of their order, and the Law of 12 files work the 12.
dr_algebra.py has the single-digit group structure; this file is the
ring structure and the r-fold module over it.
"""

from math import gcd, lcm, comb

# ----------------------------------------------------------------------
# carrier
# ----------------------------------------------------------------------

def digital_root(n):
    """Representative in 1..9; 9 stands for the class of 0."""
    return 9 if n == 0 else (n - 1) % 9 + 1


def digits(x):
    return [int(c) for c in str(x)]


def ring_digits(x):
    """Digits as ring representatives: a literal 0 is the class 9."""
    return [digital_root(int(c)) for c in str(x)]


def text(v):
    return ''.join(str(d) for d in v)


RING = list(range(1, 10))          # Z/9Z with 9 for 0


# ----------------------------------------------------------------------
# THEOREM 10: all four operations, and the ring
# ----------------------------------------------------------------------

def c_add(a, b):
    return digital_root(a + b)


def c_sub(a, b):
    return digital_root(a - b)


def c_mul(a, b):
    return digital_root(a * b)


def c_div(a, b):
    """Only defined when b is a unit; returns None otherwise."""
    if gcd(b, 9) != 1:
        return None
    return digital_root(a * pow(b, -1, 9))


def c_pow(a, b):
    return digital_root(pow(a, b, 9))


def c_neg(a):
    return digital_root(-a)


UNITS = [d for d in RING if gcd(d, 9) == 1]          # 1 2 4 5 7 8
IDEAL = [d for d in RING if gcd(d, 9) != 1]          # 3 6 9  = (3)
INVERSES = {u: digital_root(pow(u, -1, 9)) for u in UNITS}
RESIDUE_FIELD_ORDER = 3                              # Z/9Z / (3) = F_3
NILPOTENCY_INDEX = 2                                 # (3)^2 = 0


def table(op):
    """Full 9x9 table of a binary operation, as a dict."""
    return {(a, b): op(a, b) for a in RING for b in RING}


# ----------------------------------------------------------------------
# THEOREM 11: the two lattices
# ----------------------------------------------------------------------

def additive_subgroups():
    """Subgroups of (Z/9Z,+): one per divisor of 9."""
    out = {}
    for d in (1, 3, 9):
        gen = 9 // d
        out[d] = sorted({digital_root(k * gen) for k in range(1, d + 1)})
    return out


def unit_subgroups():
    """Subgroups of (Z/9Z)*: one per divisor of 6."""
    out = {}
    for d in (1, 2, 3, 6):
        step = 6 // d
        out[d] = sorted({digital_root(pow(2, k * step, 9)) for k in range(d)})
    return out


PRIMITIVE_ROOT = 2
UNIT_GROUP_ORDER = 6                   # phi(9)
SQUARES_OF_UNITS = [1, 4, 7]           # order-3 subgroup = ker(cubing)
CUBES_OF_UNITS = [1, 8]                # order-2 subgroup = ker(squaring) = {+-1}


# ----------------------------------------------------------------------
# THEOREM 12: exponentiation
# ----------------------------------------------------------------------

CARMICHAEL_9 = 6                       # lambda(9)


def multiplicative_order(d):
    """Order of a unit; None for a non-unit."""
    if gcd(d, 9) != 1:
        return None
    k, x = 1, d % 9
    while x != 1:
        x = x * d % 9
        k += 1
    return k


# ----------------------------------------------------------------------
# THEOREM 13 / 14: across the bar, under any operation
# ----------------------------------------------------------------------

def bar(v, op):
    """Column i becomes v_i o v_(r+1-i)."""
    r = len(v)
    return [op(v[i], v[r - 1 - i]) for i in range(r)]


def is_palindrome(v):
    v = list(v)
    return v == v[::-1]


def is_antipalindrome(v):
    r = len(v)
    return all(digital_root(v[i] + v[r - 1 - i]) == 9 for i in range(r))


def is_commutative(op):
    return all(op(a, b) == op(b, a) for a in RING for b in RING)


def is_anticommutative(op):
    return all(digital_root(op(a, b) + op(b, a)) == 9 for a in RING for b in RING)


# the ten operations run across the bar, commutative first
OPS = {
    'add':      c_add,
    'mul':      c_mul,
    'gcd':      lambda a, b: gcd(a, b),
    'lcm':      lambda a, b: digital_root(lcm(a, b)),
    'min':      min,
    'max':      max,
    'absdiff':  lambda a, b: abs(a - b) or 9,
    'sub':      c_sub,
    'div':      lambda a, b: c_div(a, b) if c_div(a, b) is not None else 9,
    'pow':      c_pow,
}

COMMUTATIVE = ['add', 'mul', 'gcd', 'lcm', 'min', 'max', 'absdiff']
NONCOMMUTATIVE = ['sub', 'div', 'pow']

# the worked sheet, every operation, N = 14689
SHEET = 14689
BAR_TABLE = {'add': '13331', 'mul': '95959', 'gcd': '14641', 'lcm': '98689',
             'min': '14641', 'max': '98689', 'absdiff': '84948',
             'sub': '15948', 'div': '95929', 'pow': '17919'}


# ----------------------------------------------------------------------
# THEOREM 15: the eigenspace split
# ----------------------------------------------------------------------

def palindromic_part_x2(v):
    """Twice the (+1)-eigenspace projection: v (+) reverse(v)."""
    return bar(v, c_add)


def antipalindromic_part_x2(v):
    """Twice the (-1)-eigenspace projection: v (-) reverse(v)."""
    return bar(v, c_sub)


def recover(v):
    """Reassemble v from its two projections.  2^-1 = 5 mod 9.

    Returns ring representatives, so it reproduces v exactly only when v
    is already given in them (a literal 0 digit comes back as 9).
    """
    P = palindromic_part_x2(v)
    A = antipalindromic_part_x2(v)
    return [digital_root(5 * digital_root(P[i] + A[i])) for i in range(len(v))]


def ranks(r):
    """(rank of palindromes, rank of antipalindromes) in (Z/9Z)^r."""
    return ((r + 1) // 2, r // 2)


# ----------------------------------------------------------------------
# THEOREM 16: 11^k and Pascal
# ----------------------------------------------------------------------

def pascal_row(k):
    return [comb(k, j) for j in range(k + 1)]


def eleven_power_is_palindromic(k):
    s = str(11 ** k)
    return s == s[::-1]


PASCAL_BREAKS_AT = 5                   # row 5 contains 10


